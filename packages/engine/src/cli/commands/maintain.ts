type Status = "ok" | "warn" | "fail";

interface CheckResult {
  id: string;
  status: Status;
  message: string;
  fix?: string;
}

/** Decks older than this have browser data worth refreshing before a talk. */
const STALE_DATA_DAYS = 120;

export type PackageManager = "pnpm" | "npm" | "yarn" | "bun";

/** The manager a deck uses: its lockfile first, then `packageManager`, then what launched this. */
export function detectPackageManager(root: string, env: Record<string, string | undefined> = process.env): PackageManager {
  const locks: [string, PackageManager][] = [["pnpm-lock.yaml", "pnpm"], ["package-lock.json", "npm"], ["yarn.lock", "yarn"], ["bun.lock", "bun"], ["bun.lockb", "bun"]];
  for (const [file, manager] of locks) if (existsSync(path.join(root, file))) return manager;
  try {
    const field = (JSON.parse(readFileSync(path.join(root, "package.json"), "utf8")) as { packageManager?: string }).packageManager;
    const name = field?.split("@")[0];
    if (name === "pnpm" || name === "npm" || name === "yarn" || name === "bun") return name;
  } catch {
    /* no package.json */
  }
  const agent = env.npm_config_user_agent?.split("/")[0];
  return agent === "pnpm" || agent === "yarn" || agent === "bun" ? agent : "npm";
}

function checkNode(): CheckResult {
  const major = Number.parseInt(process.versions.node, 10);
  return major >= 22 ? { id: "node", status: "ok", message: `Node ${process.versions.node}` } : { id: "node", status: "fail", message: `Node ${process.versions.node} is older than 22.`, fix: "Install Node 22 or later." };
}

function checkManager(root: string): CheckResult {
  const manager = detectPackageManager(root);
  const version = toolVersion(manager);
  return version ? { id: "package-manager", status: "ok", message: `${manager} ${version}` } : { id: "package-manager", status: "fail", message: `This deck uses ${manager}, which is not on PATH.`, fix: `Install ${manager}.` };
}

function checkShell(root: string): CheckResult[] {
  const results: CheckResult[] = [];
  const status = shellStatus(root);
  const drifted = status.filter((f) => f.state !== "current");
  for (const f of drifted) {
    const why = f.state === "missing" ? "is missing" : f.state === "outdated" ? "is from an older engine" : f.headerLost ? 'was edited and lost its "Generated by live-ish" header' : "was edited";
    results.push({ id: "shell", status: "fail", message: `${f.target} ${why}.`, fix: f.state === "edited" ? "Run `live-ish upgrade --force` to restore it." : "Run `live-ish upgrade`." });
  }
  if (!drifted.length) results.push({ id: "shell", status: "ok", message: `${status.length} shell files match the engine.` });
  if (!readManifest(root)) results.push({ id: "shell", status: "warn", message: `${MANIFEST} is missing, so an upgrade cannot tell an old file from an edited one.`, fix: "Run `live-ish upgrade --force`." });
  const { retired, foreign } = strayFiles(root);
  for (const rel of retired) results.push({ id: "shell", status: "warn", message: `${rel} is a generated file the engine no longer writes.`, fix: "Run `live-ish upgrade`." });
  for (const rel of foreign) results.push({ id: "shell", status: "warn", message: `${rel} is not generated by live-ish. An upgrade leaves it, but the engine does not know about it.` });
  return results;
}

async function checkPorts(root: string): Promise<CheckResult[]> {
  let servers: { app: string; port: number }[] = [];
  try {
    servers = readSummary(root).servers ?? [];
  } catch {
    /* not prepared yet */
  }
  const ports = [{ app: null, port: 3000 }, ...servers];
  const results: CheckResult[] = [];
  for (const { app, port } of ports) {
    if (await portAnswers(port)) results.push({ id: "ports", status: "warn", message: `Port ${port}, for ${app ?? "the deck"}, is in use.`, fix: app ? "Stop what is using it, or change this server's port in deck.config.ts." : "Stop what is using it, or pass --port." });
    else results.push({ id: "ports", status: "ok", message: `Port ${port} is free.` });
  }
  return results;
}

/** One process answers on both addresses, as a deck does. Frames depend on that pair. */
async function checkOrigins(): Promise<CheckResult> {
  const server = createServer((_req, res) => res.end("ok"));
  await new Promise<void>((resolve) => server.listen(0, resolve));
  const { port } = server.address() as AddressInfo;
  const reach = async (host: string) => {
    try {
      return (await fetch(`http://${host}:${port}/`, { signal: AbortSignal.timeout(2000) })).ok;
    } catch {
      return false;
    }
  };
  const hosts = ["localhost", "127.0.0.1"];
  const answers = await Promise.all(hosts.map(reach));
  server.close();
  const silent = hosts.filter((_, i) => !answers[i]);
  return silent.length ? { id: "origins", status: "fail", message: `${silent.join(" and ")} did not reach a local server.`, fix: "Check /etc/hosts and any proxy settings. Frames need both addresses." } : { id: "origins", status: "ok", message: "localhost and 127.0.0.1 both answer." };
}

function checkWebFeatures(): CheckResult {
  const { version, data } = installedWebFeatures();
  const newest = Object.values(data.browsers)
    .flatMap((b) => b.releases.map((r) => r.date))
    .filter((d) => d <= new Date().toISOString().slice(0, 10))
    .sort()
    .at(-1);
  const days = newest ? Math.floor((Date.now() - Date.parse(newest)) / 864e5) : Infinity;
  if (days > STALE_DATA_DAYS) return { id: "web-features", status: "warn", message: `web-features ${version} has no browser release from the last ${days} days.`, fix: "Update @live-ish/engine." };
  return { id: "web-features", status: "ok", message: `web-features ${version}, data through ${newest}.` };
}

function newestUnder(dir: string): number {
  if (!existsSync(dir)) return 0;
  return readdirSync(dir, { withFileTypes: true, recursive: true }).reduce((n, e) => (e.isFile() ? Math.max(n, statSync(path.join(e.parentPath, e.name)).mtimeMs) : n), 0);
}

function checkGenerated(root: string): CheckResult[] {
  const generated = path.join(root, ".live-ish", "deck.gen.ts");
  if (!existsSync(generated)) return [{ id: "generated", status: "warn", message: "The deck has not been prepared yet.", fix: "Run `live-ish dev` or `live-ish check`." }];
  const results: CheckResult[] = [];
  const sources = Math.max(newestUnder(path.join(root, "slides")), newestUnder(path.join(root, "demos")), statSync(path.join(root, "deck.config.ts")).mtimeMs);
  if (sources > statSync(generated).mtimeMs) results.push({ id: "generated", status: "warn", message: ".live-ish/ is older than the deck's sources.", fix: "Run `live-ish check`." });
  const runtime = path.join(root, "public", "live-ish", "demo-runtime.js");
  if (existsSync(runtime) && !readFileSync(runtime).equals(readFileSync(path.join(ENGINE, "assets", "demo-runtime.js")))) results.push({ id: "generated", status: "warn", message: "public/live-ish/ is from another engine version.", fix: "Run `live-ish check`." });
  const staleSchema = SCHEMA_FILES.some((f) => {
    const copy = path.join(root, ".live-ish", "schema", f);
    return !existsSync(copy) || !existsSync(path.join(SCHEMA_DIST, f)) || !readFileSync(copy).equals(readFileSync(path.join(SCHEMA_DIST, f)));
  });
  if (staleSchema) results.push({ id: "generated", status: "warn", message: ".live-ish/schema/ is missing or stale.", fix: "Run `live-ish schema`." });
  if (!results.length) results.push({ id: "generated", status: "ok", message: "Generated files are current." });
  return results;
}

const MARK: Record<Status, string> = { ok: "✓", warn: "▲", fail: "✖" };

export async function doctor(ctx: Ctx): Promise<ExitCode> {
  const root = requireDeck(ctx);
  const checks = [checkNode(), checkManager(root), ...checkShell(root), ...(await checkPorts(root)), await checkOrigins(), checkWebFeatures(), ...checkGenerated(root)];
  const failed = checks.some((c) => c.status === "fail");
  if (ctx.json) printJson({ ok: !failed, engine: engineVersion(), checks });
  else {
    for (const c of checks) {
      ctx.log(`${MARK[c.status]} ${c.message}`);
      if (c.fix) ctx.log(`  ${c.fix}`);
    }
    ctx.log(failed ? "doctor: problems found" : "doctor: passed");
  }
  return failed ? EXIT.findings : EXIT.ok;
}

/** The newest public schema this engine reads. */
const SCHEMA_VERSION = 1;

interface Codemod {
  from: number;
  summary: string;
  /** Rewrites the deck in place, from `from` to `from + 1`. */
  run(root: string): void;
}

/** Each breaking change to the public schema adds one entry. A deck walks them in order. */
export const CODEMODS: Codemod[] = [];

function runCodemods(root: string, log: Ctx["log"]): string[] {
  const version = readSchemaVersion(readFileSync(path.join(root, "deck.config.ts"), "utf8"));
  if (version === null) throw new CliError("schemaVersion in deck.config.ts is not a plain number.", EXIT.findings, "Set it to the version the deck was written for.");
  if (version > SCHEMA_VERSION) throw environment(`This deck has schemaVersion ${version}, and this engine reads up to ${SCHEMA_VERSION}.`, "Update @live-ish/engine.");
  const applied: string[] = [];
  for (let at = version; at < SCHEMA_VERSION; at++) {
    const step = CODEMODS.find((c) => c.from === at);
    if (!step) throw environment(`No codemod takes schemaVersion ${at} forward.`, "Upgrade through the release that made this change.");
    step.run(root);
    applied.push(step.summary);
    log(`Schema: ${step.summary}`);
  }
  return applied;
}

export async function upgrade(ctx: Ctx): Promise<ExitCode> {
  const root = requireDeck(ctx);
  const edited = shellStatus(root).filter((f) => f.state === "edited");
  if (edited.length && ctx.flags.force !== true) {
    const names = edited.map((f) => f.target);
    if (ctx.json) printJson({ ok: false, edited: names });
    else {
      ctx.log("Stopped. These generated files were edited, and an upgrade would overwrite them:");
      for (const name of names) ctx.log(`  ${name}`);
      ctx.log("Keep what you need elsewhere, then run `live-ish upgrade --force`.");
    }
    return EXIT.findings;
  }
  // Codemods first: a deck this engine cannot read stops here, with its shell as it was.
  const codemods = runCodemods(root, ctx.log);
  const { written, removed } = writeShell(root);
  const agents = refreshAgents(root, ctx.log);
  if (ctx.json) printJson({ ok: true, engine: engineVersion(), written, removed, codemods, agents });
  else {
    for (const file of written) ctx.log(`Wrote ${file}`);
    for (const file of removed) ctx.log(`Removed ${file}`);
    ctx.log(written.length || removed.length ? `Shell refreshed from @live-ish/engine ${engineVersion()}.` : `The shell already matches @live-ish/engine ${engineVersion()}.`);
    if (agents.written.length) ctx.log(`Refreshed ${agents.written.length} agent file(s).`);
  }
  return EXIT.ok;
}

const ADD: Record<PackageManager, string[]> = { pnpm: ["add", "-D"], npm: ["install", "-D"], yarn: ["add", "-D"], bun: ["add", "-d"] };
const EXEC: Record<PackageManager, string[]> = { pnpm: ["exec"], npm: ["exec", "--"], yarn: ["exec"], bun: ["x"] };

export async function addVerify(ctx: Ctx): Promise<ExitCode> {
  const root = requireDeck(ctx);
  const manager = detectPackageManager(root);
  const version = engineVersion();
  const install = [manager, ...ADD[manager], `@live-ish/verify@${version}`];
  const browser = [manager, ...EXEC[manager], "playwright", "install", "chromium"];
  if (ctx.flags["dry-run"] === true) {
    if (ctx.json) printJson({ ok: true, commands: [install, browser] });
    else for (const c of [install, browser]) ctx.log(c.join(" "));
    return EXIT.ok;
  }
  for (const [command, ...args] of [install, browser]) {
    ctx.log(`$ ${command} ${args.join(" ")}`);
    const run = spawnSync(command, args, { cwd: root, stdio: ctx.json ? ["ignore", 2, 2] : "inherit" });
    if (run.status !== 0) throw environment(`\`${command} ${args.join(" ")}\` failed.`, "Check the network, then run `live-ish add verify` again.");
  }
  if (ctx.json) printJson({ ok: true, commands: [install, browser] });
  else ctx.log("Verify is ready. Try `live-ish walk` and `live-ish capture`.");
  return EXIT.ok;
}

/** Commands that live in `@live-ish/verify`. It ships Playwright, so a deck installs it on demand. */
export const VERIFY_COMMANDS = ["capture", "og", "walk", "axe", "warmup", "perf", "parity", "backgrounds"];

export async function delegate(ctx: Ctx, command: string, argv: string[]): Promise<number> {
  // Comparing two reports reads two files, so it needs no deck: a bare checkout can run it.
  const root = command === "parity" && argv.includes("--compare") ? (findDeck(ctx.cwd) ?? ctx.cwd) : requireDeck(ctx);
  const entry = resolveFromDeck(root, "@live-ish/verify/cli");
  if (!entry) throw environment(`\`live-ish ${command}\` needs @live-ish/verify.`, "Install it with: live-ish add verify");
  const verify = (await import(pathToFileURL(entry).href)) as { run(argv: string[], context: { root: string; engineVersion: string }): Promise<number> };
  return verify.run([command, ...argv], { root, engineVersion: engineVersion() });
}
