import { readdirSync } from "node:fs";
import path from "node:path";
import type { AssembledDeck, DeckInput } from "../schema/assemble";
import type { DemoConfig } from "../schema/config";

const BEATS = ["before", "after", "single"] as const;

/** What only the speaker reads, on a beat and on each of its steps. */
function stripBeat<T extends DemoConfig["before"]>(beat: T): T {
  if (!beat) return beat;
  const { notes: _notes, ...rest } = beat;
  return { ...rest, steps: beat.steps.map(({ notes: _stepNotes, ifKeyboard: _keyboard, ...step }) => step) } as T;
}

function stripDemo(demo: DemoConfig): DemoConfig {
  const { cautions: _cautions, ...rest } = demo;
  const out: DemoConfig = { ...rest };
  if (demo.intro) {
    const { notes: _notes, ...intro } = demo.intro;
    out.intro = intro;
  }
  for (const beat of BEATS) if (demo[beat]) out[beat] = stripBeat(demo[beat]) as never;
  return out;
}

/** The deck with speaker-only text removed, for a build that has no speaker window. */
export function stripNotes(input: DeckInput): DeckInput {
  return {
    ...input,
    slides: input.slides.map(({ notes: _notes, ...slide }) => slide),
    demos: input.demos.map((d) => ({ ...d, demo: stripDemo(d.demo) })),
  };
}

/** Every line of speaker text in an assembled deck, for reading a finished build back. */
export function collectNotes({ slides, demos }: AssembledDeck): string[] {
  const paragraphs = [...slides.map((s) => s.notes), ...demos.flatMap((d) => [...d.cautions, ...d.pages.flatMap((p) => [p.notes, ...p.steps.flatMap((s) => s.notes)])])];
  return [...new Set(paragraphs.flatMap((p) => p.split(/\n\s*\n/)).map((p) => p.trim()).filter((p) => p.length > 20))];
}

/** Plain data as source. A value JSON would drop has no place in a deck's data, so it stops the build. */
function dataSource(value: unknown, where: string): string {
  return JSON.stringify(value, (key, v: unknown) => {
    if (typeof v === "function" || v instanceof RegExp) throw new Error(`live-ish: ${where} holds a ${typeof v === "function" ? "function" : "RegExp"} at "${key}". Deck data must be plain values; server code belongs in routes.ts.`);
    return v;
  });
}

/**
 * `.live-ish/deck.gen.ts` for a build with no notes. The usual module imports `demo.ts` and every
 * slide, which would bundle what they say; this one is their data, with the speaker's text removed.
 * Each `routes.ts`, `render.ts` and shell stays an import, because it holds code. None may import a
 * `demo.ts`.
 */
export function strippedDeckModule(input: DeckInput, root = process.cwd()): string {
  const stripped = stripNotes(input);
  const imports: string[] = [];
  const demos = stripped.demos.map((d, i) => {
    const { routes, render, ...rest } = d;
    const data = dataSource(rest, d.folder);
    if (routes === undefined && render === undefined) return `    ${data},`;
    if (routes !== undefined) imports.push(`import routes${i} from "../${d.folder}/routes";`);
    if (render !== undefined) imports.push(`import render${i} from "../${d.folder}/render";`);
    return `    { ...${data}${routes !== undefined ? `, routes: routes${i}` : ""}${render !== undefined ? `, render: render${i}` : ""} },`;
  });
  const dir = path.join(root, "shells");
  const shellFiles = input.shells?.length ? readdirSync(dir).filter((f) => /\.tsx?$/.test(f) && !f.endsWith(".d.ts")).sort() : [];
  shellFiles.forEach((f, i) => imports.push(`import shell${i} from "../shells/${f.replace(/\.tsx?$/, "")}";`));
  return ["// Generated by live-ish for a public build. Do not edit.", ...imports, "", "export default {", `  config: ${dataSource(stripped.config, "deck.config.ts")},`, `  slides: ${dataSource(stripped.slides, "slides")},`, "  demos: [", ...demos, "  ],", `  shells: [${shellFiles.map((_, i) => `shell${i}`).join(", ")}],`, "} as never;", ""].join("\n");
}
