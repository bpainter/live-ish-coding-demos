const ENGINE = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const ASSETS = path.join(ENGINE, "assets");
const OUT = ".live-ish";
const PUBLIC_OUT = path.join("public", "live-ish");
/** Files under public/ the page functions ask about, answered from a list so they need not carry the images. */
const LISTED = ["intro", "posters", "images", "opt"];

const write = (file: string, text: string | Buffer) => {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
};

const sorted = (dir: string, match: (name: string) => boolean) => (existsSync(dir) ? readdirSync(dir).filter(match).sort() : []);

/** `.live-ish/deck.gen.ts`: every slide and demo module, with each demo's folder. */
export function writeDeckModule(root: string): string {
  const slides = sorted(path.join(root, "slides"), (f) => /\.tsx?$/.test(f) && !f.endsWith(".d.ts"));
  const demos = sorted(path.join(root, "demos"), (f) => existsSync(path.join(root, "demos", f, "demo.ts")));
  const imports = ['import config from "../deck.config";'];
  const slideNames = slides.map((f, i) => {
    imports.push(`import slide${i} from "../slides/${f.replace(/\.tsx?$/, "")}";`);
    return `slide${i}`;
  });
  const demoEntries = demos.map((d, i) => {
    imports.push(`import demo${i} from "../demos/${d}/demo";`);
    const routes = existsSync(path.join(root, "demos", d, "routes.ts"));
    if (routes) imports.push(`import routes${i} from "../demos/${d}/routes";`);
    const hooks = existsSync(path.join(root, "demos", d, "hooks.js"));
    return `    { folder: "demos/${d}", demo: demo${i}, hooks: ${hooks}${routes ? `, routes: routes${i}` : ""} },`;
  });
  const file = path.join(root, OUT, "deck.gen.ts");
  write(file, ["// Generated by live-ish. Do not edit.", ...imports, "", "export default {", "  config,", `  slides: [${slideNames.join(", ")}],`, "  demos: [", ...demoEntries, "  ],", "};", ""].join("\n"));
  return file;
}

/** The engine's own frame files, copied into the deck's public folder. */
function copyAssets(root: string) {
  const out = path.join(root, PUBLIC_OUT);
  const files = ["demo-runtime.js", "grain.png", "frame-base.css", "shells/base.css", "shells/terminal-window.css", "terminal/player.css", "terminal/player.js"];
  for (const f of files) {
    mkdirSync(path.dirname(path.join(out, f)), { recursive: true });
    copyFileSync(path.join(ASSETS, f), path.join(out, f));
  }
}

/** Every theme the deck resolves to, by id, or a sentence naming the one it can't find. */
function resolvedThemes(root: string, { deck, slides }: AssembledDeck): Map<string, ChromeTheme> {
  // Theme values land in a stylesheet, so a file that fails the lint stops here, not at `live-ish check`.
  for (const [id, file] of customThemeFiles(deck.chrome.custom, root)) {
    const problems = lintThemeFile(JSON.parse(readFileSync(file, "utf8")));
    if (problems.length) throw new DeckError(`theme-lint: ${id}: ${problems.map((p) => `${p.field}: ${p.message}`).join(" ")}`);
  }
  const ids = new Set([deck.chrome.theme, ...slides.flatMap((s) => (s.chrome ? [s.chrome] : []))]);
  const out = new Map<string, ChromeTheme>();
  try {
    for (const id of ids) out.set(id, resolveTheme(id, deck.chrome.custom, root));
  } catch (error) {
    if (error instanceof ThemeError) throw new DeckError(`deck.config.ts: ${error.message}`);
    throw error;
  }
  return out;
}

/**
 * Theme stylesheets. All ten sit in public/live-ish/chrome/, so `?chrome=<id>` previews any of them
 * with no rebuild; the layout links only the ones the deck resolves to. A custom theme is generated
 * here, from its file and its base.
 */
function writeChrome(root: string, { deck }: AssembledDeck) {
  const out = path.join(root, PUBLIC_OUT, "chrome");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const id of builtInIds()) {
    copyFileSync(path.join(ASSETS, "chrome", `${id}.css`), path.join(out, `${id}.css`));
    copyFileSync(path.join(ASSETS, "chrome", `${id}.frame.css`), path.join(out, `${id}.frame.css`));
  }
  for (const id of customThemeFiles(deck.chrome.custom, root).keys()) {
    const theme = resolveTheme(id, deck.chrome.custom, root);
    write(path.join(out, `${id}.css`), themeCss(theme));
    write(path.join(out, `${id}.frame.css`), themeFrameCss(theme));
  }
}

/**
 * Only the fonts the deck uses reach public/: the copy slides' pair, and each resolved theme's. A
 * preview through `?chrome=` of any other theme falls back to the system stack in its theme file, and
 * asks for no file. `next dev` and LIVE_ISH_ALL_FONTS=1 (the conformance runs) copy every family, so
 * those previews show the real faces.
 */
function writeFonts(root: string, deck: AssembledDeck["deck"], themes: Map<string, ChromeTheme>) {
  const out = path.join(root, PUBLIC_OUT, "fonts");
  rmSync(out, { recursive: true, force: true });
  const names = new Set<string>(deck.theme.fonts ? [] : ["Inter", "JetBrains Mono"]);
  for (const theme of themes.values()) {
    for (const font of [theme.fonts.sans, theme.fonts.mono]) if (typeof font === "string" && FONT_FAMILIES[font]) names.add(font);
  }
  if (process.env.LIVE_ISH_ALL_FONTS === "1" || process.env.NODE_ENV === "development") for (const name of Object.keys(FONT_FAMILIES)) names.add(name);
  for (const name of names) {
    const font = FONT_FAMILIES[name];
    for (const face of [...font.faces.map((f) => f.file), "OFL.txt"]) {
      const to = path.join(root, "public", fontUrl(font, face));
      mkdirSync(path.dirname(to), { recursive: true });
      copyFileSync(path.join(ASSETS, "fonts", font.id, face), to);
    }
  }
  const custom = [...themes.values()].flatMap((t) => [t.fonts.sans, t.fonts.mono]).flatMap((font) => (typeof font === "string" ? [] : font.files.map((f) => `@font-face { font-family: "${font.family}"; font-weight: ${f.weight}; font-display: swap; src: url("${f.src}") format("woff2"); }`)));
  const deckFaces = Object.entries(deck.theme.fonts ?? {}).flatMap(([slot, files]) => (files ?? []).map((src) => `@font-face { font-family: "Deck ${slot}"; font-weight: ${/(?:bold|-?700)/i.test(src) ? 700 : 400}; font-display: swap; src: url("${src}") format("woff2"); }`));
  write(path.join(root, PUBLIC_OUT, "fonts.css"), [fontFaceCss(names), ...custom, ...deckFaces].filter(Boolean).join("\n") + "\n");
}

/**
 * `theme.extends`, `theme.fonts` and `theme.tokens`, last in the cascade. `:root:root` outranks the
 * engine's own :root, whatever order the two stylesheets arrive in.
 */
function writeDeckTheme(root: string, { deck }: AssembledDeck) {
  const parts: string[] = [];
  if (deck.theme.extends !== "default") {
    const file = path.resolve(root, deck.theme.extends);
    if (!existsSync(file)) throw new DeckError(`deck.config.ts: theme.extends names ${deck.theme.extends}, which does not exist.`);
    parts.push(readFileSync(file, "utf8"));
  }
  const tokens = Object.entries(deck.theme.tokens).map(([k, v]) => `  ${k}: ${v};`);
  const fonts = deck.theme.fonts ?? {};
  if (fonts.sans?.length) tokens.push(`  --deck-font-sans: "Deck sans", system-ui, sans-serif;`);
  if (fonts.mono?.length) tokens.push(`  --deck-font-mono: "Deck mono", ui-monospace, monospace;`);
  if (tokens.length) parts.push(`:root:root {\n${tokens.join("\n")}\n}`);
  write(path.join(root, PUBLIC_OUT, "deck.css"), parts.join("\n") + "\n");
}

/** Per-demo frame images, keyed by the `data-section-bg` the composer writes. */
function writeBackgrounds(root: string, { demos }: AssembledDeck) {
  const rules = demos.filter((d) => d.background).map((d) => {
    const value = d.background!;
    return `html[data-section-bg="${d.id}"] { --frame-image: ${isBackgroundFile(value) ? `url("${value}")` : value}; --frame-wash: linear-gradient(rgb(255 255 255 / 0.4), rgb(255 255 255 / 0.4)); }`;
  });
  write(path.join(root, PUBLIC_OUT, "backgrounds.css"), rules.join("\n") + "\n");
}

async function writeQr(root: string, { slides }: AssembledDeck) {
  for (const slide of slides) {
    if (slide.copy?.kind !== "closing" || !slide.copy.url) continue;
    write(path.join(root, PUBLIC_OUT, "qr", `${slide.id}.svg`), (await qrSvg(slide.copy.url)).svg);
  }
}

/** Lines of code the way a meter counts them: the file as written, less blank and comment-only lines. */
export function countLines(source: string): number {
  let n = 0;
  let inBlock = false;
  for (const raw of source.split("\n")) {
    const line = raw.trim();
    if (inBlock) {
      if (line.includes("*/")) inBlock = false;
      continue;
    }
    if (!line || line.startsWith("//")) continue;
    if (line.startsWith("/*")) {
      if (!line.includes("*/")) inBlock = true;
      continue;
    }
    n++;
  }
  return n;
}

/** `meter.source` is a glob on the demo folder: "before/*.js". Any other source keeps its typed value. */
export function computeMeters(root: string, { demos }: Pick<AssembledDeck, "demos">): Record<string, string> {
  const out: Record<string, string> = {};
  for (const demo of demos) {
    for (const page of demo.pages) {
      for (const step of page.steps) {
        const meter = step.meter;
        if (!meter) continue;
        const m = /^(?:(.+)\/)?\*\.js$/.exec(meter.source);
        if (!m) {
          out[meterKey(demo.id, meter.source)] = meter.value;
          continue;
        }
        const dir = path.join(root, demo.folder, m[1] ?? "");
        let n = 0;
        for (const f of sorted(dir, (name) => name.endsWith(".js"))) n += countLines(readFileSync(path.join(dir, f), "utf8"));
        out[meterKey(demo.id, meter.source)] = `${n} line${n === 1 ? "" : "s"}`;
      }
    }
  }
  return out;
}

function writeMeters(root: string, assembled: AssembledDeck) {
  write(path.join(root, OUT, "meters.json"), JSON.stringify(computeMeters(root, assembled), null, 2) + "\n");
}

function writeSupport(root: string, { demos }: AssembledDeck) {
  const file = path.join(root, OUT, "support.json");
  const previous = existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as SupportFile) : null;
  if (!demos.some((d) => d.support)) return write(file, JSON.stringify({ package: "web-features", version: "", toolDates: {}, demos: {} }, null, 2) + "\n");
  const { version, data } = installedWebFeatures();
  write(file, JSON.stringify(computeSupport(demos, data, version, previous?.toolDates ?? {}), null, 2) + "\n");
}

function listFiles(base: string, dir: string): string[] {
  const abs = path.join(base, dir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { withFileTypes: true, recursive: true })
    .filter((e) => e.isFile() && !e.name.startsWith("."))
    .map((e) => "/" + path.relative(base, path.join(e.parentPath, e.name)).split(path.sep).join("/"))
    .sort();
}

/** Runs last, so the hashes cover everything the steps above wrote. */
function writeFileLists(root: string) {
  const base = path.join(root, "public");
  const versions: Record<string, string> = {};
  for (const url of listFiles(base, "live-ish")) versions[url] = createHash("sha256").update(readFileSync(path.join(base, url))).digest("hex").slice(0, 8);
  write(path.join(root, OUT, "asset-versions.json"), JSON.stringify(versions, null, 2) + "\n");
  write(path.join(root, OUT, "public-files.json"), JSON.stringify(LISTED.flatMap((d) => listFiles(base, d)), null, 2) + "\n");
  const images = path.join(root, OUT, "images.json");
  if (!existsSync(images)) write(images, "{}\n");
}

/** The deck's name in storage keys and channels: `live-ish:<deck>:*`. */
export function deckId(title: string): string {
  return title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "deck";
}

/** What `withDeck()` needs before any bundler runs. */
function writeSummary(root: string, input: DeckInput, assembled: AssembledDeck) {
  const addresses = assembled.demos.flatMap((d) => d.routes ?? []).map((r) => (typeof r.path === "string" ? { path: r.path } : { regex: r.path.source }));
  const { hosts, presenter, reader, title } = assembled.deck;
  write(path.join(root, OUT, "deck.json"), JSON.stringify({ firstSlide: assembled.slides[0].id, deckId: deckId(title), hosts, presenter, reader, addresses, demoFiles: demoFiles(root), demos: input.demos.map((d) => d.demo.id) }, null, 2) + "\n");
}

/**
 * Every file of every demo folder but `demo.ts`, which holds the notes in source and which nothing
 * reads at request time. Listed one by one, so no server function carries it: Turbopack's trace
 * includes win over its excludes, and its globs have no negation.
 */
function demoFiles(root: string): string[] {
  return listFiles(root, "demos").filter((f) => path.posix.basename(f) !== "demo.ts").map((f) => `.${f}`);
}

/** `.live-ish/analytics.gen.ts`: the deck's own analytics module as a lazy import, or nothing. */
function writeAnalytics(root: string, { deck }: AssembledDeck) {
  const { provider, script } = deck.analytics;
  const type = "(() => Promise<{ default?: () => void }>) | null";
  let value = "null";
  if (provider === "custom") {
    if (!script) throw new DeckError('deck.config.ts: analytics.provider "custom" needs analytics.script, a client module path.');
    if (!existsSync(path.join(root, script))) throw new DeckError(`deck.config.ts: analytics.script "${script}" is not in the deck folder.`);
    value = `() => import(${JSON.stringify(`../${path.posix.normalize(script).replace(/\.tsx?$/, "")}`)})`;
  }
  write(path.join(root, OUT, "analytics.gen.ts"), `// Generated by live-ish. Do not edit.\nexport const load: ${type} = ${value};\n`);
}

/** A public build has no speaker window to show notes in, unless the deck publishes them. */
export function keepsNotes({ deck }: AssembledDeck, target: "local" | "deployed"): boolean {
  return target === "local" || deck.presenter.onHost || deck.reader.notes;
}

/** Inside this repo, rebuilds the engine's CSS when a source file is newer. A published engine ships it built. */
async function refreshEngineCss() {
  const styles = path.join(ENGINE, "styles");
  const builder = path.join(ENGINE, "scripts", "build-css.mjs");
  if (!existsSync(styles) || !existsSync(builder)) return;
  const dist = path.join(ENGINE, "dist", "engine.css");
  const built = existsSync(dist) ? statSync(dist).mtimeMs : 0;
  const sources = readdirSync(styles, { recursive: true, encoding: "utf8" }).map((f) => path.join(styles, f));
  if (sources.every((f) => statSync(f).mtimeMs <= built)) return;
  await import(pathToFileURL(builder).href);
}

/**
 * Everything a deck derives from its own folder: the generated deck module, the engine's frame files
 * under public/live-ish/, and the generated data under .live-ish/. In-process, and run by `withDeck()`
 * on every `next dev` and `next build`, so a deck has no separate setup step. A `deployed` target
 * that keeps no notes gets a deck module with them removed, so they reach no bundle.
 */
export async function prepareDeck(root: string, target: "local" | "deployed" = "local"): Promise<AssembledDeck> {
  process.env.LIVE_ISH_DECK_ROOT = root;
  if (!existsSync(path.join(root, "deck.config.ts"))) throw new DeckError(`No deck.config.ts in ${root}.`);
  await refreshEngineCss();
  const file = writeDeckModule(root);
  const input = ((await import(pathToFileURL(file).href)) as { default: DeckInput }).default;
  const assembled = assembleDeck(input);
  const themes = resolvedThemes(root, assembled);
  if (!keepsNotes(assembled, target)) write(file, strippedDeckModule(input));
  writeAnalytics(root, assembled);
  copyAssets(root);
  writeChrome(root, assembled);
  writeFonts(root, assembled.deck, themes);
  writeDeckTheme(root, assembled);
  writeBackgrounds(root, assembled);
  await writeQr(root, assembled);
  writeMeters(root, assembled);
  writeSupport(root, assembled);
  writeFileLists(root);
  writeSummary(root, input, assembled);
  return assembled;
}
