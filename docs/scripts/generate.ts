// Everything on the site that is generated, never hand-edited. Run before dev, build and tests.
//
//   .gen/fragments/*.md    Tables pages pull in with <Generated name="x" />
//   .gen/pages/errors/*    One page per rule id
//   .gen/theme-swatches.css   One class per theme color
//   app/(deck) and friends    The engine's shell, for the live deck
//   deck.config.ts, slides/, demos/, public/images/   The starter, for the live deck
//   public/*.md, llms.txt, sitemap.xml, robots.txt    Copies for tools and crawlers
import { execFileSync } from "node:child_process";
import { copyFileSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { allRules, rulePage } from "../../packages/engine/src/lib/validate";
import { RULE_IDS, TIERS } from "../../packages/engine/src/lib/validate/catalog";
import { keyHelpFor, KEY_HELP } from "../../packages/engine/src/lib/keys";
import { budgetFragment, cell, configFragment, parityFragment, schemaFragment } from "../lib/fragments";
import { NAV } from "../lib/nav";
import { allPages, DOCS, GEN, markdownHref, pageHref, REPO, SITE, toMarkdown } from "../lib/source";

const ENGINE = path.join(REPO, "packages", "engine");
const STARTER = path.join(REPO, "examples", "starter");
const PUBLIC = path.join(DOCS, "public");

function put(file: string, text: string) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}

const fragment = (name: string, text: string) => put(path.join(GEN, "fragments", `${name}.md`), `${text.trim()}\n`);
const readJson = <T>(file: string) => JSON.parse(readFileSync(file, "utf8")) as T;
const cli = (...args: string[]) => execFileSync(process.execPath, [path.join(ENGINE, "bin", "live-ish.mjs"), ...args], { encoding: "utf8", cwd: STARTER });

/** Fails the build if a page needs a page that is gone. */
function rulePages() {
  const tierNames: Record<string, string> = { integrity: "Integrity", fit: "Fit", support: "Support", style: "Style" };
  for (const id of RULE_IDS) {
    const source = rulePage(id);
    if (!source) throw new Error(`The rule "${id}" has no packages/engine/rules/${id}.md.`);
    const body = source.replace(/^# .*\n+/, "");
    const tier = Object.entries(TIERS).find(([, ids]) => ids.includes(id))?.[0] ?? "";
    const frontmatter = `---\ntitle: ${id}\noutcome: When you finish this page, you will know what the ${id} rule checks and how to fix a finding.\n---\n\n`;
    put(path.join(GEN, "pages", "errors", `${id}.md`), `${frontmatter}${body.trim()}\n\nTier: ${tierNames[tier]}. To read this page offline, run \`live-ish explain ${id}\`. See [all rules](/errors) and [how tiers work](/verification).\n`);
  }
  const summaries = new Map(allRules.map((rule) => [rule.id, rule.summary]));
  const section = (tier: string) => {
    const ids = [...(TIERS as Record<string, readonly string[]>)[tier]].sort();
    return [`## ${tierNames[tier]}`, "", "| Rule | What it checks |", "|---|---|", ...ids.map((id) => `| [\`${id}\`](/errors/${id}) | ${cell(summaries.get(id) ?? "")} |`), ""].join("\n");
  };
  fragment("rule-index", Object.keys(TIERS).map(section).join("\n"));
}

interface ThemeFile {
  id: string;
  name: string;
  traits: string[];
  tokens: Record<string, string>;
  code: Record<string, string>;
  fonts: { sans: string; mono: string };
  motion?: { fade?: number; effect?: string };
}

/** The built-in themes, from their one source. */
function themes() {
  const dir = path.join(ENGINE, "themes");
  const list = readdirSync(dir)
    .filter((f) => f.endsWith(".json") && !f.includes("schema"))
    .map((f) => readJson<ThemeFile>(path.join(dir, f)));
  // Glass first, because it is the default. `live-ish themes` keeps this order.
  const order = (JSON.parse(cli("themes", "--json")) as { themes: { id: string }[] }).themes.map((t) => t.id);
  list.sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));

  const table = readFileSync(path.join(DOCS, "generated", "themes-table.md"), "utf8").replace(/<!--.*?-->\n*/s, "");
  fragment("theme-table", table);

  const swatches = ["--chrome-backdrop", "--chrome-card-surface", "--chrome-ink", "--chrome-accent"];
  const css: string[] = ["/* Generated by scripts/generate.ts from packages/engine/themes. Do not edit. */"];
  const gallery: string[] = [];
  for (const theme of list) {
    for (const token of swatches) css.push(`.swatch--${theme.id}-${token.replace("--chrome-", "")} { background: ${theme.tokens[token]}; }`);
    gallery.push(
      `## ${theme.name}`,
      "",
      `<ThemeSwatches id="${theme.id}" />`,
      "",
      `Set it with \`chrome: { theme: "${theme.id}" }\`. Preview it on the live deck at [/s/faq-after?chrome=${theme.id}](/s/faq-after?chrome=${theme.id}).`,
      "",
      theme.traits.map((t) => `- ${t}.`).join("\n"),
      "",
      "| Token | Value |",
      "|---|---|",
      ...swatches.map((token) => `| \`${token}\` | \`${cell(theme.tokens[token])}\` |`),
      `| Fonts | ${theme.fonts.sans}, ${theme.fonts.mono} |`,
      "",
    );
  }
  put(path.join(GEN, "theme-swatches.css"), `${css.join("\n")}\n`);
  fragment("theme-gallery", gallery.join("\n"));
  return list;
}

function commands() {
  const help = cli("--help");
  const rows = help
    .split("\n")
    .filter((line) => /^ {2}\S/.test(line))
    .map((line) => {
      const [usage, summary] = line.trim().split(/\s{2,}/);
      return `| \`live-ish ${usage.replace(/\|/g, "\\|")}\` | ${summary ?? "Needs `@live-ish/verify`."} |`;
    });
  fragment("cli-table", ["| Command | What it does |", "|---|---|", ...rows].join("\n"));

  const { actions, assert } = JSON.parse(cli("actions", "--json")) as { actions: { type: string; fields: string[]; summary: string }[]; assert: { forms: { form: string; example: string; meaning: string }[] } };
  fragment("action-table", ["| Action | Fields | What it does |", "|---|---|---|", ...actions.map((a) => `| \`${a.type}\` | ${a.fields.map((f) => `\`${f}\``).join(", ")} | ${cell(a.summary)} |`)].join("\n"));
  fragment("assert-table", ["| Form | Example | Passes when |", "|---|---|---|", ...assert.forms.map((f) => `| \`${cell(f.form)}\` | \`${cell(f.example)}\` | ${cell(f.meaning)} |`)].join("\n"));
}

function keys() {
  const row = (r: (typeof KEY_HELP)[number]) => `| ${r.keys.map((k) => `\`${k}\``).join(r.keys[0] === "Shift" ? " + " : ", ")} | ${cell(r.action)} |`;
  fragment("keys-presenter", ["| Keys | What they do |", "|---|---|", ...keyHelpFor("presenter").map(row)].join("\n"));
  fragment("keys-reader", ["| Keys | What they do |", "|---|---|", ...keyHelpFor("reader").map(row)].join("\n"));
}

/** Lets the docs be a deck: the starter's content, and the shell's routes under a route group. */
function liveDeck() {
  for (const dir of ["slides", "demos"]) {
    rmSync(path.join(DOCS, dir), { recursive: true, force: true });
    cpSync(path.join(STARTER, dir), path.join(DOCS, dir), { recursive: true });
  }
  cpSync(path.join(STARTER, "public", "images"), path.join(PUBLIC, "images"), { recursive: true });
  // The starter's notes are public anyway, and a public presenter is what proves one origin.
  const config = readFileSync(path.join(STARTER, "deck.config.ts"), "utf8").replace(/\}\);\s*$/, "  presenter: { onHost: true },\n});\n");
  put(path.join(DOCS, "deck.config.ts"), `// Generated by docs/scripts/generate.ts from examples/starter. Do not edit.\n${config}`);

  const shell = path.join(ENGINE, "shell", "app");
  const app = path.join(DOCS, "app");
  const group = path.join(app, "(deck)");
  rmSync(group, { recursive: true, force: true });
  for (const entry of ["layout.tsx", "not-found.tsx", "s", "present", "speaker"]) cpSync(path.join(shell, entry), path.join(group, entry), { recursive: true });
  for (const entry of ["demos", "live-ish-address", "%5Fhealth"]) {
    rmSync(path.join(app, entry), { recursive: true, force: true });
    cpSync(path.join(shell, entry), path.join(app, entry), { recursive: true });
  }
}

function assets() {
  for (const name of ["demo-slide.png", "themes.png"]) {
    const file = path.join(DOCS, "assets", name);
    if (existsSync(file)) {
      mkdirSync(path.join(PUBLIC, "assets"), { recursive: true });
      copyFileSync(file, path.join(PUBLIC, "assets", name));
    }
  }
}

/** The site for tools: a Markdown copy of each page, `llms.txt`, a sitemap and `robots.txt`. */
function copies() {
  const pages = allPages();
  for (const page of pages) put(path.join(PUBLIC, markdownHref(page.slug)), toMarkdown(page));
  const bySlug = new Map(pages.map((page) => [page.slug, page]));
  const line = (slug: string) => {
    const page = bySlug.get(slug);
    if (!page) throw new Error(`The nav names "${slug}", and no page has that address.`);
    return `- [${page.title}](${SITE}${markdownHref(slug)}): ${page.outcome}`;
  };
  const errors = pages.filter((page) => page.slug.startsWith("errors/"));
  const llms = [
    "# Live-ish",
    "",
    "> Live-ish runs slides and scripted demos of code and UI from one web app. Each click plays one step in a real page and highlights the code behind it.",
    "",
    ...NAV.flatMap((group) => [`## ${group.section}`, "", ...group.slugs.map(line), ""]),
    "## Rule pages",
    "",
    ...errors.map((page) => `- [${page.title}](${SITE}${markdownHref(page.slug)})`),
    "",
  ];
  put(path.join(PUBLIC, "llms.txt"), llms.join("\n"));
  const urls = pages.map((page) => `  <url><loc>${SITE}${pageHref(page.slug)}</loc></url>`);
  put(path.join(PUBLIC, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`);
  put(path.join(PUBLIC, "robots.txt"), `User-agent: *\nAllow: /\nDisallow: /demos/\nDisallow: /live-ish/\nDisallow: /present\nDisallow: /speaker\n\nSitemap: ${SITE}/sitemap.xml\n`);
}

rmSync(GEN, { recursive: true, force: true });
rmSync(PUBLIC, { recursive: true, force: true });
liveDeck();
rulePages();
const list = themes();
commands();
keys();
fragment("config-table", configFragment(readJson(path.join(ENGINE, "dist", "schema", "deck-config.json"))));
fragment("demo-fields", schemaFragment(readJson(path.join(ENGINE, "dist", "schema", "demo.json"))));
fragment("budgets", budgetFragment(path.join(REPO, "packages", "verify", "budgets.json")));
fragment("parity-table", parityFragment(path.join(REPO, "parity", "matrix.json")));
fragment("theme-count", String(list.length));
assets();
copies();
console.log(`generated ${allPages().length} pages, ${RULE_IDS.length} rules, ${list.length} themes`);
